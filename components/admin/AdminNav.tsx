export default function AdminNav() {
  const pathname = usePathname();
  const [mobileOpen, setMobileOpen] = useState(false);
  const [permissions, setPermissions] = useState<string[] | null>(null);

  useEffect(() => {
    fetch("/api/auth/check")
      .then((r) => (r.ok ? r.json() : null))
      .then((data) => {
        // A session predating per-page permissions answers without the field;
        // treat that as "unknown" rather than "none", so the nav explains
        // itself instead of rendering an empty bar.
        setPermissions(Array.isArray(data?.permissions) ? data.permissions : null);
      })
      .catch(() => setPermissions(null));
  }, []);

  // Until permissions load, show nothing rather than flashing links the
  // user may not be allowed to open.
  const navLinks = permissions
    ? allNavLinks.filter((link) =>
        grantsPermission(permissions, permissionForPath(link.href)),
      )
    : [];

  // Distinguishes "still loading" from "logged in but nothing to show" —
  // an empty sidebar is indistinguishable from a broken deploy otherwise.
  const emptyNavNotice =
    navLinks.length === 0 ? (
      <p className="px-3 py-2 text-xs leading-relaxed text-white/50">
        {permissions === null
          ? "Se încarcă meniul..."
          : "Nicio pagină disponibilă pentru contul dumneavoastră. Deconectați-vă și autentificați-vă din nou, iar dacă problema persistă cereți permisiuni administratorului."}
      </p>
    ) : null;

  if (pathname === "/admin/login") return null;

  return (
    <>
      {/* ── SIDEBAR desktop ── */}
      <aside className="hidden md:flex flex-col w-56 shrink-0 h-screen sticky top-0 bg-foreground text-white overflow-hidden">
        {/* Logo */}
        <div className="px-5 py-5 border-b border-white/10">
          <span className="font-serif text-lg font-semibold tracking-tight">
            TechnicalDent
          </span>
          <p className="text-[10px] text-white/40 uppercase tracking-widest mt-0.5">
            Admin
          </p>
        </div>

        {/* Nav links */}
        <nav className="flex-1 px-3 py-4 space-y-0.5 overflow-y-auto admin-sidebar-scroll">
          {navLinks.map((link) => {
            const isActive =
              link.href === "/admin"
                ? pathname === "/admin"
                : pathname.startsWith(link.href);
            return (
              <Link
                key={link.href}
                href={link.href}
                className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm transition-colors ${
                  isActive
                    ? "bg-white/15 text-white font-medium"
                    : "text-white/60 hover:text-white hover:bg-white/10"
                }`}
              >
                {link.icon}
                {link.label}
              </Link>
            );
          })}
          {emptyNavNotice}
        </nav>

        {/* Bottom */}
        <div className="px-3 py-4 border-t border-white/10 space-y-1">
          <Link
            href="/"
            className="flex items-center gap-3 px-3 py-2 rounded-lg text-sm text-white/60 hover:text-white hover:bg-white/10 transition-colors"
          >
            <svg
              className="w-4 h-4"
              fill="none"
              viewBox="0 0 24 24"
              strokeWidth={1.8}
              stroke="currentColor"
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M10.5 19.5L3 12m0 0l7.5-7.5M3 12h18"
              />
            </svg>
            Vezi site-ul
          </Link>
          <Link
            href="/admin/cont"
            className={`flex items-center gap-3 px-3 py-2 rounded-lg text-sm transition-colors ${
              pathname === "/admin/cont"
                ? "bg-white/15 text-white font-medium"
                : "text-white/60 hover:text-white hover:bg-white/10"
            }`}
          >
            <svg
              className="w-4 h-4"
              fill="none"
              viewBox="0 0 24 24"
              strokeWidth={1.8}
              stroke="currentColor"
            >
              <path
                strokeLinecap="round"
                strokeLinejoin="round"
                d="M15.75 6a3.75 3.75 0 11-7.5 0 3.75 3.75 0 017.5 0zM4.501 20.118a7.5 7.5 0 0114.998 0A17.933 17.933 0 0112 21.75c-2.676 0-5.216-.584-7.499-1.632z"
              />
            </svg>
            Contul meu
          </Link>
          <div className="px-3">
            <LogoutButton />
          </div>
        </div>
      </aside>

      {/* ── TOP BAR mobile ── */}
      <div className="md:hidden sticky top-0 z-50 bg-foreground text-white shadow-lg">
        <div className="flex h-13 items-center justify-between px-4">
          <button
            onClick={() => setMobileOpen(!mobileOpen)}
            className="p-1.5 rounded-md hover:bg-white/10"
            aria-label="Meniu"
          >
            <div className="w-5 h-4 relative flex flex-col justify-between">
              <span
                className={`block h-[2px] w-full bg-white rounded-full transition-all duration-300 origin-center ${mobileOpen ? "translate-y-[7px] rotate-45" : ""}`}
              />
              <span
                className={`block h-[2px] w-full bg-white rounded-full transition-all duration-200 ${mobileOpen ? "opacity-0 scale-x-0" : ""}`}
              />
              <span
                className={`block h-[2px] w-full bg-white rounded-full transition-all duration-300 origin-center ${mobileOpen ? "-translate-y-[7px] -rotate-45" : ""}`}
              />
            </div>
          </button>
          <span className="font-serif text-sm font-semibold">
            TechnicalDent Admin
          </span>
          <LogoutButton />
        </div>

        {/* Mobile dropdown — max-h is the remaining viewport height below the
            top bar (h-13 = 3.25rem), with its own scroll so every page stays
            reachable no matter how many nav links get added. */}
        <div
          className={`transition-all duration-300 ${mobileOpen ? "max-h-[calc(100dvh-3.25rem)] overflow-y-auto border-t border-white/10" : "max-h-0 overflow-hidden"}`}
        >
          <nav className="px-3 py-3 space-y-0.5">
            {navLinks.map((link) => {
              const isActive =
                link.href === "/admin"
                  ? pathname === "/admin"
                  : pathname.startsWith(link.href);
              return (
                <Link
                  key={link.href}
                  href={link.href}
                  onClick={() => setMobileOpen(false)}
                  className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors ${
                    isActive
                      ? "bg-white/15 text-white font-medium"
                      : "text-white/60 hover:text-white hover:bg-white/10"
                  }`}
                >
                  {link.icon}
                  {link.label}
                </Link>
              );
            })}
            {emptyNavNotice}
            <Link
              href="/admin/cont"
              onClick={() => setMobileOpen(false)}
              className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm text-white/60 hover:text-white hover:bg-white/10"
            >
              Contul meu
            </Link>
            <Link
              href="/"
              className="flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm text-white/60 hover:text-white hover:bg-white/10"
            >
              ← Vezi site-ul
            </Link>
          </nav>
        </div>
      </div>
    </>
  );
}
